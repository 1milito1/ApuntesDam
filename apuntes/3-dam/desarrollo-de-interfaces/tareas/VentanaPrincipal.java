    public VentanaPrincipal() {
        initComponents();
        
        URL urlIcono = getClass().getResource("/tarea1padelapp/Imagenes/raqueta-de-padel.png");
        
        if (urlIcono != null){
            ImageIcon icono = new ImageIcon(urlIcono);
            this.setIconImage(icono.getImage());
            
        }else {
            System.err.println("Error: no se pudo encontrar la imagen");
        }
        
        try {
            File fichero = new File("help/helpset.hs");
            URL hsURL = fichero.toURI().toURL();
            helpset = new HelpSet(getClass().getClassLoader(), hsURL);
            hb = helpset.createHelpBroker();

            // Dejamos configurado F1 para siempre
            hb.enableHelpKey(this.getContentPane(), "ventana_principal", helpset);
        } catch (Exception e) { 
            System.err.println("Error en ayuda" + e.getMessage());
        }
    }

