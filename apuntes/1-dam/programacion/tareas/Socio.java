public class Socio {

	private int id;
	private String nombre;
	private String email;
	private String direccion;

	public int getId() {
		return this.id;
	}

	public String getNombre() {
		return this.nombre;
	}

	public String getEmail() {
		return this.email;
	}

	public String getDireccion() {
		return this.direccion;
	}

}